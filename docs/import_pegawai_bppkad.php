function nextKP($tmt_pns, $today_str) {
    if ( ! $tmt_pns) return null;
    $pns   = new DateTime($tmt_pns);
    $today = new DateTime($today_str);
    $m = (int) $pns->format('n');
    $y = (int) $pns->format('Y') + 4;
    $kp = ($m <= 6) ? new DateTime("{$y}-04-01") : new DateTime("{$y}-10-01");
    while ($kp <= $today) $kp->modify('+4 years');
    return $kp->format('Y-m-d');
}

function nextKGB($tmt_pppk, $today_str) {
    if ( ! $tmt_pppk) return null;
    $tmt   = new DateTime($tmt_pppk);
    $today = new DateTime($today_str);
    $m = (int) $tmt->format('n');
    $y = (int) $tmt->format('Y') + 2;
    $kgb = ($m <= 6) ? new DateTime("{$y}-04-01") : new DateTime("{$y}-10-01");
    while ($kgb <= $today) $kgb->modify('+2 years');
    return $kgb->format('Y-m-d');
}

function dateOrNull($v) {
    $v = trim((string) $v);
    return preg_match('/^\d{4}-\d{2}-\d{2}$/', $v) ? $v : null;
}

function cleanDigitsOrNull($v) {
    $v = preg_replace('/\D+/', '', (string) $v);
    return $v === '' ? null : $v;
}

function normName($v) {
    return strtoupper(preg_replace('/\s+/', ' ', trim((string) $v)));
}

function maritalStatus($kd_stawin, $jk) {
    $kd = trim((string) $kd_stawin);
    if ($kd === '2') return 'KAWIN';
    if ($kd === '3') return $jk === 'P' ? 'JANDA' : 'DUDA';
    return 'BELUM_KAWIN';
