function pnsTppId($gol_code, $eselon) {
    $eselon = strtoupper(trim((string) $eselon));
    if ($eselon === '2B') return 33;
    if ($eselon === '3A') return 37;
    if ($eselon === '3B') return 39;
    if ($eselon === '4A' || $eselon === '4B') return 43;
    $level = substr((string) $gol_code, 0, 1);
    if ($level === '1') return 89;
    if ($level === '2') return 78;
    return 72;
}

function pppkTppId($kd_pangkat) {
    $kd = trim((string) $kd_pangkat);
    if (in_array($kd, ['9','10','11','12','13','14','15','16','17'], true)) return 90;
    if (in_array($kd, ['7','8'], true)) return 91;
    return 92;
}

function parseRows($csv) {
    $rows = [];
    foreach (preg_split('/\R/', trim($csv)) as $line) {
        if (trim($line) === '') continue;
        $rows[] = str_getcsv($line, '|');
    }
    return $rows;
}

function ensureJabatan($pdo, $kode, $nama, $eselon) {
    $q = $pdo->prepare('SELECT id FROM ref_jabatan WHERE nama_jabatan=? LIMIT 1');
    $q->execute([$nama]);
    $id = $q->fetchColumn();
    if ($id) return (int) $id;

    $ins = $pdo->prepare('INSERT INTO ref_jabatan (kode_jabatan, nama_jabatan, jenis_jabatan, eselon, is_active) VALUES (?, ?, \'STRUKTURAL\', ?, 1)');
    $ins->execute([$kode, $nama, $eselon]);
    return (int) $pdo->lastInsertId();
}

